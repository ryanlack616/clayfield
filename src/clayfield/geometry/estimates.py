"""Mesh size and memory estimates for safe export planning."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class MeshEstimate:
    """Expected topology and approximate NumPy storage requirements."""

    rows: int
    columns: int
    vertex_count: int
    triangle_count: int
    vertex_bytes: int
    face_bytes: int
    working_bytes: int

    @property
    def total_bytes(self) -> int:
        """Estimated persistent mesh array storage."""
        return self.vertex_bytes + self.face_bytes

    @property
    def total_mebibytes(self) -> float:
        """Persistent mesh storage in MiB."""
        return self.total_bytes / (1024.0 * 1024.0)

    @property
    def working_mebibytes(self) -> float:
        """Conservative generation working-set estimate in MiB."""
        return self.working_bytes / (1024.0 * 1024.0)


def estimate_solid_mesh(rows: int, columns: int) -> MeshEstimate:
    """Estimate the topology generated by ``generate_solid_mesh``."""
    if rows < 2 or columns < 2:
        raise ValueError("Mesh resolution must be at least 2 by 2")

    vertex_count = 2 * rows * columns
    perimeter_edges = 2 * rows + 2 * columns - 4
    triangle_count = 4 * (rows - 1) * (columns - 1) + 2 * perimeter_edges
    vertex_bytes = vertex_count * 3 * 4
    face_bytes = triangle_count * 3 * 8
    persistent_bytes = vertex_bytes + face_bytes

    return MeshEstimate(
        rows=rows,
        columns=columns,
        vertex_count=vertex_count,
        triangle_count=triangle_count,
        vertex_bytes=vertex_bytes,
        face_bytes=face_bytes,
        # Mesh creation, orientation, Trimesh validation, and export verification
        # keep several topology and coordinate arrays alive simultaneously.
        # Validation and export can retain Trimesh adjacency, bounds, area,
        # component, and temporary topology arrays simultaneously. Keep this
        # conservative enough to cover observed validation peaks.
        working_bytes=persistent_bytes * 20,
    )


def recommended_resolution(rows: int, columns: int, max_triangles: int) -> tuple[int, int]:
    """Return an aspect-preserving resolution at or below a triangle budget."""
    if rows < 2 or columns < 2:
        raise ValueError("Mesh resolution must be at least 2 by 2")
    if max_triangles < 12:
        raise ValueError("Triangle budget is too small")
    current = estimate_solid_mesh(rows, columns)
    if current.triangle_count <= max_triangles:
        return rows, columns
    scale = (max_triangles / current.triangle_count) ** 0.5
    suggested_rows = max(2, int(rows * scale))
    suggested_columns = max(2, int(columns * scale))
    while estimate_solid_mesh(suggested_rows, suggested_columns).triangle_count > max_triangles:
        if suggested_rows >= suggested_columns and suggested_rows > 2:
            suggested_rows -= 1
        elif suggested_columns > 2:
            suggested_columns -= 1
        else:
            break
    return suggested_rows, suggested_columns
